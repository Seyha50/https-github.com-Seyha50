import 'dart:async';

import 'package:bbusrd104/models/category_model.dart';
import 'package:bbusrd104/services/category_service.dart';
import 'package:get/get.dart';

class CategoryController extends GetxController {
  // Add your controller logic here
  
  // fields 
  final CategoryService service ; 

  final isLoading = false.obs; // Observable to track loading state
  final categories = <CategoryModel>[].obs;
  final txtSearch = ''.obs; // Observable keyword for filtering
  StreamSubscription <List<CategoryModel>>? _subscription; // Subscription to the category stream
  // constructor
  CategoryController(this.service);
  @override
  void onInit() {
    super.onInit();
    showCategories(); // Load categories when the controller is initialized
  }

  // add category
  Future<bool> addCategory({required String categoryName, String? description}) 
  async {
    try {
      isLoading.value = true; // Set loading state to true before operation
      final category = CategoryModel(
        id: '', // ID will be generated by Firestore
        categoryName: categoryName,
        description: description,
      );
      await service.addCategory(category);
      return true;
    } catch (ex) {
      Get.snackbar('Error', 'Failed to add category: ${ex.toString()}',
      snackPosition: SnackPosition.BOTTOM,
      duration: Duration(seconds: 5)
      );
      return false; // Return false to indicate failure
    } finally {
      isLoading.value = false; // Set loading state to false after operation 
    }
    
  }
  void showCategories() {
      _subscription = service.getCategories().listen((data) {
      categories.assignAll(data); // Update the observable list with new data
      }, 
      onError: (error) {
        Get.snackbar('Error', 'Failed to load categories: ${error.toString()}',
        snackPosition: SnackPosition.BOTTOM,
        duration: Duration(seconds: 5)
        );
      },
    );
  }
  List<CategoryModel> get filterCategories {
    final keyword = txtSearch.value.trim().toLowerCase();
    if (keyword.isEmpty) {
      return categories; // Return all categories if the search keyword is empty
    }
    return categories.where((category){
      return category.categoryName.trim().toLowerCase().contains(keyword);
     
    }).toList(); // Return the filtered list of categories
  }


  void searchCategory(String value) {
    txtSearch.value = value; // Update the search keyword
  }
    // update category
  Future<bool> updateCategory({required String categoryId, required String categoryName, String? description}) 
  async {
    try {
      isLoading.value = true; // Set loading state to true before operation
      final category = CategoryModel(
        id: categoryId, // ID will be generated by Firestore
        categoryName: categoryName,
        description: description,
      );
      await service.updateCategory(category);
      return true;
    } catch (ex) {
      Get.snackbar('Error', 'Failed to update category: ${ex.toString()}',
      snackPosition: SnackPosition.BOTTOM,
      duration: Duration(seconds: 5)
      );
      return false; // Return false to indicate failure
    } finally {
      isLoading.value = false; // Set loading state to false after operation 
    }
    
  }
  @override
  void onClose() {
    _subscription?.cancel();
    super.onClose();
  }
  
}